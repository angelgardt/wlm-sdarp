# Объявление функции: аргументы, тело, возврат (последнее выражение)
z_score <- function(x, na_rm = TRUE) {
  if (na_rm) x <- x[!is.na(x)]
  (x - mean(x)) / sd(x)  # явный return не обязателен
}

# Функции — объекты первого класса: можно передавать, возвращать, хранить
apply_z <- function(data, col_name) {
  data[[col_name]] <- z_score(data[[col_name]])
  data  # возврат изменённого объекта
}

# Анонимные функции и замыкания (как в Lua)
make_multiplier <- function(factor) {
  function(x) x * factor  # возвращает функцию, «помнящую» factor
}
times_10 <- make_multiplier(10)
times_10(5)  # [1] 50

