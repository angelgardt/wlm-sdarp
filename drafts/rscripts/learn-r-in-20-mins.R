# %>% (pipe) передаёт результат слева как первый аргумент справа
# В современном R можно использовать |> (нативный пайп), но %>% пока гибче

# Ключевые глаголы dplyr:
df_processed <- df %>%
  # filter: строки по условию
  filter(!is.na(score), group == "Trt") %>%
  # mutate: новые/изменённые столбцы
  mutate(
    score_z = (score - mean(score)) / sd(score),
    log_score = log(score + 1)  # +1 чтобы избежать log(0)
  ) %>%
  # select: выбор столбцов (помогает при больших данных)
  select(id, group, score_z) %>%
  # arrange: сортировка
  arrange(desc(score_z))

# group_by + summarise: агрегация по группам (аналог SQL GROUP BY)
summary_stats <- df %>%
  filter(!is.na(score)) %>%
  group_by(group) %>%
  summarise(
    n = n(),
    mean_score = mean(score),
    sd_score = sd(score),
    ci_lower = mean_score - qt(0.975, df = n-1) * sd_score / sqrt(n),
    ci_upper = mean_score + qt(0.975, df = n-1) * sd_score / sqrt(n),
    .groups = "drop"  # явно указываем поведение группировки
  )

